"""
flarex.phantom
==============

A SYNTHETIC flame-video generator with exact ground truth.

READ THIS BEFORE USING ANY NUMBER PRODUCED FROM THIS MODULE
-----------------------------------------------------------
Nothing here is NASA data. Nothing here is an experimental observation.
No result computed on a phantom may be presented as a finding about
microgravity combustion, and every figure derived from it must carry the
label defined in `SYNTHETIC_LABEL`.

WHAT IT IS FOR
--------------
NASA PSI data requires individual registration and is not redistributable,
so the archived BASS-II video cannot be bundled with an open repository.
That leaves a real engineering problem: how do you demonstrate that the
segmentation, feature extraction and change-point code is *correct* before
a user has downloaded the data?

The answer used here is the standard one from medical imaging and remote
sensing: a phantom. A phantom is an object with exactly known properties,
imaged through the same processing chain, so that measured-versus-true
error is attributable to the instrument and the algorithm rather than to
the unknown scene. It answers "does my measurement pipeline work?" It does
not answer "what is true about flames?"

So the phantom gives FLARE-X two honest, non-fabricated metric families:

  * segmentation accuracy   IoU and Dice against the exact generating mask
  * event detection accuracy precision/recall of detected change points
                            against the exact commanded step frames

and it gives zero combustion findings.

WHAT THE PHANTOM IMITATES, AND WHY
----------------------------------
The geometry and protocol follow the *documented* BASS-II opposed-flow rod
configuration so that the code is exercised on the right kind of signal:

  * a horizontal rod with a flame near one end
  * a staircase of commanded opposed-flow velocities, stepped downward
    with a dwell at each level, ending in extinction
    (protocol per Link et al. 2018, doi:10.1038/s41598-017-18398-4)
  * a yellow-to-blue colour shift and a fall in brightness as flow falls
  * flame elongation and increasing standoff at low flow
  * a burned-in telemetry overlay strip, because the real BASS-II video
    carried one (nitrogen flow rate, fan voltage, hot-wire anemometer
    reading, radiometer signal), and a segmenter that has never seen an
    overlay will happily segment the text

The *functional forms* linking flow to appearance are invented smooth
curves chosen to be plausible and monotone. They are not fits to data and
they encode no physical claim. Their only job is to produce a signal with
the right structure so the detector can be scored.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

__all__ = [
    "PhantomConfig",
    "PhantomRun",
    "generate_phantom_run",
    "iou",
    "dice",
    "SYNTHETIC_LABEL",
]

SYNTHETIC_LABEL = (
    "SYNTHETIC PHANTOM - NOT NASA DATA - NOT AN EXPERIMENTAL OBSERVATION. "
    "Generated by flarex.phantom to measure pipeline accuracy against exact "
    "ground truth. Any combustion interpretation of this figure is invalid."
)


@dataclass
class PhantomConfig:
    width: int = 760                  # matches the documented BASS-II video width
    height: int = 480                 # matches the documented BASS-II video height
    fps: float = 15.0
    seed: int = 20261114              # Space Apps 2026 hackathon date, for reproducibility

    # commanded opposed-flow staircase, cm/s, stepped downward to extinction
    flow_steps_cm_s: tuple[float, ...] = (7.6, 5.0, 3.2, 2.0, 1.2, 0.7, 0.45)
    dwell_frames: int = 45
    ignition_frames: int = 20
    post_extinction_frames: int = 25

    # geometry, in image pixels
    rod_y: int = 300
    rod_half_thickness: int = 7
    flame_anchor_x: int = 470

    overlay_box: tuple[int, int, int, int] = (0, 0, 760, 34)
    noise_sigma: float = 0.012
    jpeg_like_blur: float = 1.1


@dataclass
class PhantomRun:
    frames: np.ndarray                 # (T, H, W, 3) float32 in [0,1]
    truth_masks: np.ndarray            # (T, H, W) bool  - exact generating mask
    commanded_flow_cm_s: np.ndarray    # (T,)
    step_change_frames: list[int]      # exact frames where the command changed
    extinction_frame: int | None
    config: PhantomConfig
    label: str = SYNTHETIC_LABEL
    truth_features: dict[str, np.ndarray] = field(default_factory=dict)

    @property
    def n_frames(self) -> int:
        return int(self.frames.shape[0])

    @property
    def time_s(self) -> np.ndarray:
        return np.arange(self.n_frames) / self.config.fps


def _ellipse_mask(h: int, w: int, cx: float, cy: float,
                  a: float, b: float, taper: float = 0.0) -> np.ndarray:
    """Teardrop-ish blob: an ellipse with an optional downstream taper."""
    yy, xx = np.mgrid[0:h, 0:w]
    dx = (xx - cx) / max(a, 1e-3)
    dy = (yy - cy) / max(b, 1e-3)
    if taper > 0:
        widen = 1.0 + taper * np.clip(dx, 0, None)
        dy = dy / np.maximum(widen, 1e-3)
    return (dx ** 2 + dy ** 2) <= 1.0


def generate_phantom_run(config: PhantomConfig | None = None) -> PhantomRun:
    """Build the synthetic run. Deterministic given the seed."""
    cfg = config or PhantomConfig()
    rng = np.random.default_rng(cfg.seed)
    h, w = cfg.height, cfg.width

    flows: list[float] = []
    step_frames: list[int] = []
    flows.extend([cfg.flow_steps_cm_s[0]] * cfg.ignition_frames)
    for k, v in enumerate(cfg.flow_steps_cm_s):
        if k > 0:
            step_frames.append(len(flows))
        flows.extend([v] * cfg.dwell_frames)
    extinction_frame = len(flows)
    flows.extend([cfg.flow_steps_cm_s[-1]] * cfg.post_extinction_frames)
    flow = np.asarray(flows, dtype=float)
    n = flow.size

    v_hi = float(max(cfg.flow_steps_cm_s))
    v_lo = float(min(cfg.flow_steps_cm_s))
    # unit-free "closeness to the low-velocity limit"; 0 at high flow, 1 at the last step
    prox = np.clip((v_hi - flow) / max(v_hi - v_lo, 1e-6), 0.0, 1.0)

    frames = np.zeros((n, h, w, 3), dtype=np.float32)
    masks = np.zeros((n, h, w), dtype=bool)
    truth_area = np.zeros(n)
    truth_len = np.zeros(n)
    truth_standoff = np.zeros(n)

    for i in range(n):
        img = np.zeros((h, w, 3), dtype=np.float32)

        # duct background and fuel rod
        img[:, :, :] = 0.035
        img[cfg.rod_y - cfg.rod_half_thickness:cfg.rod_y + cfg.rod_half_thickness, :, :] = 0.10

        if i < extinction_frame:
            p = float(prox[i])
            if i < cfg.ignition_frames:
                ramp = (i + 1) / cfg.ignition_frames
            else:
                ramp = 1.0

            # invented monotone appearance model - see module docstring
            semi_a = (34.0 + 26.0 * p) * ramp          # elongates toward the limit
            semi_b = (21.0 - 5.0 * p) * ramp           # narrows slightly
            standoff = (4.0 + 15.0 * p) * ramp         # lifts off the surface
            bright = (0.92 - 0.55 * p) * ramp          # dims toward the limit
            chi = 0.55 - 1.05 * p                      # yellow -> blue

            cx = cfg.flame_anchor_x - 24.0 * p
            cy = cfg.rod_y - cfg.rod_half_thickness - standoff - semi_b

            m = _ellipse_mask(h, w, cx, cy, semi_a, semi_b, taper=0.25 * (1 - p))
            masks[i] = m

            yy, xx = np.mgrid[0:h, 0:w]
            rr = np.sqrt(((xx - cx) / max(semi_a, 1e-3)) ** 2 +
                         ((yy - cy) / max(semi_b, 1e-3)) ** 2)
            core = np.clip(1.0 - rr, 0.0, 1.0) ** 0.7

            # chi = (R-B)/(R+B) -> pick R and B that realise it at this brightness
            r_w = (1.0 + chi) / 2.0
            b_w = (1.0 - chi) / 2.0
            g_w = 0.45 + 0.25 * max(chi, 0.0)
            img[..., 0] += bright * core * r_w * 2.0
            img[..., 1] += bright * core * g_w * 1.6
            img[..., 2] += bright * core * b_w * 2.0

            truth_area[i] = float(m.sum())
            ys, xs = np.nonzero(m)
            truth_len[i] = float(xs.max() - xs.min()) if xs.size else 0.0
            truth_standoff[i] = standoff

        # burned-in telemetry overlay: bright text-like blocks the segmenter
        # must be told to ignore, exactly as in the archived video
        x0, y0, x1, y1 = cfg.overlay_box
        img[y0:y1, x0:x1, :] = 0.02
        rng_overlay = np.random.default_rng(cfg.seed + i)
        for bx in range(x0 + 8, x1 - 40, 46):
            wdt = int(rng_overlay.integers(14, 32))
            img[y0 + 10:y0 + 24, bx:bx + wdt, :] = 0.97

        img += rng.normal(0.0, cfg.noise_sigma, img.shape).astype(np.float32)
        frames[i] = np.clip(img, 0.0, 1.0)

    if cfg.jpeg_like_blur > 0:
        try:
            from scipy.ndimage import gaussian_filter
            for i in range(n):
                frames[i] = gaussian_filter(frames[i], (cfg.jpeg_like_blur,
                                                        cfg.jpeg_like_blur, 0))
        except ImportError:
            pass

    return PhantomRun(
        frames=frames, truth_masks=masks, commanded_flow_cm_s=flow,
        step_change_frames=step_frames, extinction_frame=extinction_frame,
        config=cfg,
        truth_features={"area_px": truth_area,
                        "length_px": truth_len,
                        "standoff_px": truth_standoff},
    )


def iou(pred: np.ndarray, truth: np.ndarray) -> float:
    """Intersection over union. NaN when both masks are empty (undefined, not 1.0)."""
    p, t = pred.astype(bool), truth.astype(bool)
    union = np.logical_or(p, t).sum()
    if union == 0:
        return float("nan")
    return float(np.logical_and(p, t).sum() / union)


def dice(pred: np.ndarray, truth: np.ndarray) -> float:
    """Dice / F1 on pixels. NaN when both masks are empty."""
    p, t = pred.astype(bool), truth.astype(bool)
    denom = p.sum() + t.sum()
    if denom == 0:
        return float("nan")
    return float(2.0 * np.logical_and(p, t).sum() / denom)
